function uiIcon(name, size) {
  const inner = UI_ICONS[name] || UI_ICONS.info;
  const s = size ? ` width="${size}" height="${size}"` : '';
  return `<svg class="ui-icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"${s}>${inner}</svg>`;
}

function hydrateIcons(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-icon]').forEach((el) => {
    if (el.getAttribute('data-hydrated') === '1') return;
    const name = el.getAttribute('data-icon');
    const size = el.getAttribute('data-size');
    el.innerHTML = uiIcon(name, size ? Number(size) : undefined);
    el.setAttribute('data-hydrated', '1');
  });
}

window.uiIcon = uiIcon;
window.hydrateIcons = hydrateIcons;
document.addEventListener('DOMContentLoaded', () => hydrateIcons());
